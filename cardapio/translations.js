  function deepClone(value) {
    return JSON.parse(JSON.stringify(value || {}));
  }

  function applyConfig(baseConfig, language) {
    const result = deepClone(baseConfig);
    const translations = config[language] || {};
    Object.entries(translations).forEach(([path, value]) => {
      const parts = path.split(".");
      let target = result;
      for (const part of parts.slice(0, -1)) {
        if (target == null || target[part] === undefined) return;
        target = target[part];
      }
      const key = parts[parts.length - 1];
      if (target && Object.prototype.hasOwnProperty.call(target, key)) {
        target[key] = value;
      }
    });
    return result;
  }

  function getLanguage() {
    const supported = ["pt", "en", "es"];
    const fromUrl = new URLSearchParams(window.location.search).get("lang");
    let selected = supported.includes(fromUrl) ? fromUrl : "";
    if (!selected) {
      try {
        const saved = window.localStorage.getItem("sr-ofrelio-language");
        if (supported.includes(saved)) selected = saved;
      } catch (_) {}
    }
    if (!selected) selected = "pt";
    if (supported.includes(fromUrl)) {
      try { window.localStorage.setItem("sr-ofrelio-language", selected); } catch (_) {}
    }
    return selected;
  }

